package org.cog.hymnchtv.utils

/** Minimal HTML escaping for text inserted into WebView content. */
object HtmlText {
    @JvmStatic
    fun escape(text: String): String = buildString(text.length) {
        for (c in text) {
            when (c) {
                '&' -> append("&amp;")
                '<' -> append("&lt;")
                '>' -> append("&gt;")
                '"' -> append("&quot;")
                '\'' -> append("&#39;")
                else -> append(c)
            }
        }
    }
}
